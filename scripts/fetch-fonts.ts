/**
 * Download the popup fonts from Bunny Fonts into src/assets/fonts and write
 * fonts.css. The fonts ship inside the extension; nothing loads from Bunny at
 * runtime. Re-run after changing FAMILY or WEIGHTS: `bun run fonts`.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const FAMILY = "inter";
const WEIGHTS = [400, 500, 700];
const SUBSET = "latin";
const OUT_DIR = join(import.meta.dir, "..", "src", "assets", "fonts");

const css = await fetch(
  `https://fonts.bunny.net/css?family=${FAMILY}:${WEIGHTS.join(",")}`,
).then((r) => r.text());

const blocks = css.split("@font-face").slice(1);
const faces: string[] = [];
await mkdir(OUT_DIR, { recursive: true });

for (const block of blocks) {
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
  if (!url || !url.includes(`-${SUBSET}-`)) continue;

  const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
  const style = block.match(/font-style:\s*(\w+)/)?.[1] ?? "normal";
  const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
  const file = url.split("/").pop()!;

  const data = await fetch(url).then((r) => r.arrayBuffer());
  await writeFile(join(OUT_DIR, file), new Uint8Array(data));

  faces.push(`@font-face {
  font-family: "Inter";
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url("./${file}") format("woff2");${range ? `\n  unicode-range: ${range};` : ""}
}`);
  console.log(`saved ${file} (${data.byteLength} bytes)`);
}

await writeFile(
  join(OUT_DIR, "fonts.css"),
  `/* Generated by scripts/fetch-fonts.ts from Bunny Fonts (fonts.bunny.net). */\n\n${faces.join("\n\n")}\n`,
);
